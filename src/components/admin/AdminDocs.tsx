/* ─── Рендер ─── */

/**
 * Спільний рендер плюс єдиний власний блок — схема адмінки. Решта типів
 * малюється тим самим кодом, що й довідка, тому два розділи не розповзаються
 * по вигляду.
 */
function Blocks({ blocks }: { blocks: Block[] }) {
  const out: React.ReactNode[] = [];
  let buf: BaseBlock[] = [];
  const flush = (key: string) => {
    if (buf.length) {
      out.push(<BaseBlocks key={key} blocks={buf} />);
      buf = [];
    }
  };
  blocks.forEach((b, i) => {
    if (b.t === "map") {
      flush(`b${i}`);
      out.push(<AdminMap key={`m${i}`} />);
    } else {
      buf.push(b);
    }
  });
  flush("last");
  return <>{out}</>;
}

