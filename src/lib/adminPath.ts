/**
 * Адреса адмінки.
 *
 * `/admin` — стандартний шлях, який сканери перебирають першим. Реальний шлях
 * задається змінною NEXT_PUBLIC_ADMIN_PATH і підставляється рерайтом у
 * next.config.ts, а nginx віддає 404 на прямий /admin.
 *
 * ⚠️ Це НЕ заміна паролю: шлях видно в JS-бандлі сторінок адмінки (а вони
 * вантажаться лише за самим цим шляхом). Захищає від шуму автоматичних
 * сканерів, не від цілеспрямованої атаки — пароль лишається основним замком.
 */
const raw = process.env.NEXT_PUBLIC_ADMIN_PATH?.trim().replace(/^\/+|\/+$/g, "");

export const ADMIN_BASE = raw ? `/${raw}` : "/admin";
export const ADMIN_LOGIN = `${ADMIN_BASE}/login`;
